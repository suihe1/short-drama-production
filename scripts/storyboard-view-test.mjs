const data = buildView(board, boardPath, production, boardPath);
assert.equal(data.shots.length,4);
assert.equal(data.shots[2].start,3.5);
assert.equal(data.shots[3].start,0);
assert.equal(data.shots[0].variants.length,2);
assert.equal(data.shots[0].image,null);
assert.equal(data.shots[0].variants[0].video,null);
